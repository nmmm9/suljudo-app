export const SCALE = ['상관없음', '1점', '2점', '3점', '4점', '5점'] as const;
const CUSTOM: Record<string, string> = { age: '나이', height: '키', weight: '체중' };

export type QType =
  | 'choice' | 'vs' | 'scale' | 'text' | 'area' | 'unit' | 'age' | 'height' | 'weight';

export type Question = {
  kind: 'q';
  key: string;
  label: string;
  type: QType;
  section: string;
  options?: string[];
  multi?: boolean;
  /** 'A VS B' 문항은 라벨 자체가 선택지라 별도 라벨을 그리지 않는다. */
  bare?: boolean;
  unit?: string;
  placeholder?: string;
};
export type Heading = { kind: 'heading'; label: string };
export type Item = Question | Heading;
export type Section = { tab: string; title: string; items: Item[]; count: number };

function parse(line: string, tab: string): Item {
  if (line[0] === '@') {
    const t = line.slice(1) as QType;
    return { kind: 'q', key: tab + '·' + CUSTOM[line.slice(1)], label: CUSTOM[line.slice(1)], type: t, section: tab };
  }
  if (line[0] === '#') return { kind: 'heading', label: line.slice(1) };

  let multi = false;
  if (line[0] === '*') { multi = true; line = line.slice(1); }

  const i = line.indexOf(':');
  let label = line, rest = '';
  if (i > -1) { label = line.slice(0, i).trim(); rest = line.slice(i + 1).trim(); }

  const base = { kind: 'q' as const, section: tab, key: tab + '·' + label, label };
  if (rest === '') {
    return line.includes(' VS ')
      ? { ...base, key: tab + '·' + line, label: line, type: 'vs', options: line.split(' VS '), bare: true }
      : { ...base, type: 'text', placeholder: PLACEHOLDER[label] };
  }
  if (rest === ':') return { ...base, type: 'area' };
  if (rest === '점수') return { ...base, type: 'scale', options: [...SCALE] };
  if (rest[0] === '~') return { ...base, type: 'unit', unit: rest.slice(1) };
  if (rest.includes(' / ')) return { ...base, type: 'choice', options: rest.split(' / '), multi };
  if (rest.includes(' VS ')) return { ...base, type: 'vs', options: rest.split(' VS ') };
  return { ...base, type: 'text', placeholder: PLACEHOLDER[label] };
}

type Row = [tab: string, title: string, lines: string[]];

export const SECTIONS: Section[] = (RAW as Row[]).map(([tab, title, lines]) => {
  const items = lines.map((l) => parse(l, tab));
  return { tab, title, items, count: items.filter((x) => x.kind === 'q').length };
});

export const QUESTIONS: Question[] = SECTIONS.flatMap((s) =>
  s.items.filter((x): x is Question => x.kind === 'q')
);

export const TOTAL = QUESTIONS.length;
export const BY_KEY = new Map(QUESTIONS.map((q) => [q.key, q]));
